    private static final int[] ZEROS = new int[64];

    public static int bonusOf(Piece piece, int square, boolean endgame) {
        int[] table = tableFor(piece.getPieceType(), endgame);
        return table[indexFor(piece.getPieceSide(), square)];
    }

    private static int[] tableFor(PieceType type, boolean endgame) {
        return switch (type) {
            case KNIGHT -> KNIGHT;
            case PAWN -> PAWN;
            case BISHOP -> BISHOP;
            case ROOK -> ROOK;
            case QUEEN -> QUEEN;
            case KING -> endgame ? KING_ENDGAME : KING;
            default -> ZEROS;
        };
    }

    private static int indexFor(Side side, int square) {
        return side == Side.WHITE ? square ^ 56 : square;
    }
